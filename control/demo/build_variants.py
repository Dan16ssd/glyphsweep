    for page in ("shop.html", "checkout.html", "about.html"):
        s = open(os.path.join(HERE, page), encoding="utf-8").read()
        for src in sorted(T, key=len, reverse=True):
            s = s.replace(src, T[src][code])
        s = s.replace("Noto+Sans+Lao", f"Noto+Sans+{FONT[code]}").replace('"Noto Sans Lao"', f'"Noto Sans {FONT[code]}"')
        s = s.replace('<html lang="lo">', f'<html lang="{code}">')
        s = s.replace("a Lao storefront", f"a {FONT[code]} storefront (generated by build_variants.py)")
        left = [c for c in s if 0x0E80 <= ord(c) <= 0x0EFF]
        assert not left, f"{d}/{page}: untranslated Lao left: {''.join(left)[:40]}"
        open(os.path.join(HERE, d, page), "w", encoding="utf-8", newline="\n").write(s)
